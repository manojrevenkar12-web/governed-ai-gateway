"""aigw: run, evaluate and audit the gateway.

aigw serve            run the gateway (uvicorn aigw.main:app), configured by AIGW_* variables
aigw evaluate         data protection, load and overhead, failover, budget race, simulated month
aigw gate             fail if reports/evaluation.json misses a service-level objective
aigw audit-verify     walk the audit chain and report the first broken entry, if any
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

import psycopg
from psycopg.rows import dict_row

# Service-level objectives the platform commits to (docs/team/OPERATIONS.md). CI holds every change to them.
SLO = {
    "dlp_heldout_precision": 0.99,
    "dlp_heldout_recall": 0.99,
    "overhead_p95_ms_at_8": 25.0,
    "failover_success": 1.0,
    "budget_overspend_pct": 0.0,
}


def evaluate(database_url: str, redis_url: str, out: Path, quick: bool = False) -> dict:
    from aigw.eval import dlp_eval, load, usage

    out.mkdir(parents=True, exist_ok=True)
    result = {"dlp": dlp_eval.run()}
    result["load"] = {
        str(c): load.load(database_url, redis_url, requests=1000 if quick else 3000, concurrency=c)
        for c in (8, 32)
    }
    result["failover"] = load.failover(database_url, redis_url)
    result["budget_race"] = load.budget_race(database_url, redis_url)
    usage.simulate(database_url, redis_url)
    month = usage.report(database_url, out)
    result["simulated_month"] = {
        "total_spend": month["total_spend"],
        "teams": month["teams"],
        "budget_exhausted": month["budget_exhausted"],
        "provider_incident": month["provider_incident"],
    }
    (out / "evaluation.json").write_text(json.dumps(result, indent=2, default=str) + "\n")
    _markdown(result, out / "EVALUATION.md")
    return result


def gate(report: dict) -> list[str]:
    problems = []
    held = report["dlp"]["held_out"]
    if held["precision"] < SLO["dlp_heldout_precision"]:
        problems.append(f"data protection precision {held['precision']:.3f} < {SLO['dlp_heldout_precision']}")
    if held["recall"] < SLO["dlp_heldout_recall"]:
        problems.append(f"data protection recall {held['recall']:.3f} < {SLO['dlp_heldout_recall']}")
    p95 = report["load"]["8"]["overhead_ms"]["p95"]
    if p95 > SLO["overhead_p95_ms_at_8"]:
        problems.append(f"gateway overhead p95 {p95:.1f} ms > {SLO['overhead_p95_ms_at_8']} ms")
    if any(r["errors"] for r in report["load"].values()):
        problems.append("errors under load")
    f = report["failover"]
    if f["succeeded"] / f["requests"] < SLO["failover_success"] or not f["primary_breaker_open"]:
        problems.append("requests failed while a provider was down, or the breaker did not open")
    if report["budget_race"]["reservations"]["overspend_pct"] > SLO["budget_overspend_pct"]:
        problems.append("a team overspent its budget under concurrent load")
    return problems


def _markdown(r: dict, path: Path) -> None:
    d, h = r["dlp"]["development"], r["dlp"]["held_out"]
    nc = r["dlp"]["development_without_context_rules"]
    lines = [
        "# Evaluation",
        "",
        "Generated by `aigw evaluate`. CI runs it on every push and `aigw gate` holds the "
        "results to the service-level objectives in `aigw/cli.py`.",
        "",
        "## Data protection",
        "",
        "| Corpus | Cases | Precision | Recall |",
        "|---|---:|---:|---:|",
        f"| Development | {d['cases']:,} | {d['precision']:.1%} | {d['recall']:.1%} |",
        f"| Development, without the context rule for card numbers | {nc['cases']:,} | {nc['precision']:.1%} | {nc['recall']:.1%} |",
        f"| Held out (formats and wording never tuned on) | {h['cases']:,} | {h['precision']:.1%} | {h['recall']:.1%} |",
        "",
        "| Kind (held out) | Planted | Found | False alarms |",
        "|---|---:|---:|---:|",
    ]
    for k, v in h["per_kind"].items():
        lines.append(f"| {k} | {v['planted']} | {v['found']} | {v['false_alarms']} |")
    lines += [
        "",
        "## Overhead and throughput",
        "",
        "One gateway process on a 2-vCPU machine shared with PostgreSQL, Redis and the load generator; mock "
        "models answer in 40 ms. Overhead is the time spent in the gateway itself.",
        "",
        "| Concurrent requests | Throughput | Overhead p50 | p95 | p99 | Errors |",
        "|---:|---:|---:|---:|---:|---:|",
    ]
    for c, v in r["load"].items():
        o = v["overhead_ms"]
        lines.append(
            f"| {c} | {v['throughput_rps']:.0f}/s | {o['p50']:.1f} ms | {o['p95']:.1f} ms | {o['p99']:.1f} ms | {v['errors']} |"
        )
    f = r["failover"]
    b = r["budget_race"]
    lines += [
        "",
        "## Provider failure",
        "",
        f"The primary provider failed every call: {f['succeeded']} of {f['requests']} requests succeeded, "
        f"{f['served_by']['backup']} served by the backup, the primary's breaker "
        f"{'opened' if f['primary_breaker_open'] else 'did NOT open'}.",
        "",
        "## Budgets under concurrency",
        "",
        "300 requests, 64 at a time, against a $0.05 budget.",
        "",
        "| Method | Admitted | Refused | Spent | Overspend |",
        "|---|---:|---:|---:|---:|",
    ]
    for name, v in b.items():
        lines.append(
            f"| {name.replace('_', ' ')} | {v['admitted']} | {v['refused_402']} | ${v['spent_usd']:.4f} | {v['overspend_pct']}% |"
        )
    lines += ["", "## A simulated month", "", "See [USAGE.md](USAGE.md)."]
    path.write_text("\n".join(lines) + "\n")


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(
        prog="aigw", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("command", choices=["serve", "evaluate", "gate", "audit-verify"])
    parser.add_argument("--quick", action="store_true")
    parser.add_argument("--port", type=int, default=8080)
    args = parser.parse_args(argv)
    db = os.environ.get("AIGW_DATABASE_URL", "postgresql://postgres@127.0.0.1:5432/aigw")
    rd = os.environ.get("AIGW_REDIS_URL", "redis://127.0.0.1:6379/0")
    reports = Path(os.environ.get("AIGW_REPORTS", "reports"))
    if args.command == "serve":
        sys.exit(
            subprocess.call(
                [
                    sys.executable,
                    "-m",
                    "uvicorn",
                    "aigw.main:app",
                    "--host",
                    "0.0.0.0",
                    "--port",
                    str(args.port),
                    "--no-access-log",
                ]
            )
        )
    if args.command == "evaluate":
        evaluate(db, rd, reports, args.quick)
        print(f"wrote {reports / 'evaluation.json'}")
    elif args.command == "gate":
        problems = gate(json.loads((reports / "evaluation.json").read_text()))
        for p in problems:
            print(f"GATE: {p}")
        if problems:
            sys.exit(1)
        print("gate: every service-level objective met")
    elif args.command == "audit-verify":
        from aigw import audit

        with psycopg.connect(db, row_factory=dict_row) as conn:
            ok, n, problem = audit.verify(conn)
        print(f"{n} entries checked: {'intact' if ok else 'BROKEN: ' + problem}")
        sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
